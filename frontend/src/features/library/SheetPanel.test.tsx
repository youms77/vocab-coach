import { screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'

import {
  detail,
  exercise,
  report,
  sheetVersion,
  usageSheet,
} from '../../test/fixtures'
import { apiErrorResponse, mockApi } from '../../test/mockApi'
import { renderApp } from '../../test/renderApp'

const term = detail(1, 'to account for')

async function openSheet() {
  await userEvent.click(await screen.findByRole('button', { name: 'Show the usage sheet' }))
}

describe('usage sheet on the term page', () => {
  it('stays hidden until asked, with a warning before discovery', async () => {
    const calls = mockApi({
      'GET /items/1': detail(1, 'to account for', { status: 'queued' }),
      'GET /items/1/sheet': sheetVersion(),
      'GET /items/1/exercises': [],
    })
    renderApp('/library/items/1')
    expect(await screen.findByText(/gives away the meaning/)).toBeInTheDocument()
    expect(screen.queryByText('tenir compte de')).not.toBeInTheDocument()
    expect(calls.some((c) => c.path.startsWith('/items/1/sheet'))).toBe(false)
    await openSheet()
    expect(await screen.findByText('tenir compte de')).toBeInTheDocument()
    expect(screen.getByText('Sheet ready')).toBeInTheDocument()
    expect(screen.getByText(/generated by gemini \(test-model, prompt enrichment.v1\)/)).toBeInTheDocument()
  })

  it('saves an edit with the version it started from', async () => {
    const calls = mockApi({
      'GET /items/1': term,
      'GET /items/1/sheet': sheetVersion(),
      'GET /items/1/exercises': [],
      'PUT /items/1/sheet': () =>
        Response.json(sheetVersion({ enrichment_id: 8, version: 2, edited_by_user: true })),
    })
    renderApp('/library/items/1')
    expect(screen.queryByText(/gives away/)).not.toBeInTheDocument()
    await openSheet()
    await userEvent.click(await screen.findByRole('button', { name: 'Edit the sheet' }))
    const notes = screen.getByLabelText('When and how to use it')
    await userEvent.type(notes, '  Followed by a noun.  ')
    // An empty row is left out of what is sent.
    await userEvent.click(screen.getByRole('button', { name: 'Add: Word family' }))
    await userEvent.click(screen.getByRole('button', { name: 'Save the sheet' }))
    expect(await screen.findByText('Saved as a new version.')).toBeInTheDocument()
    const put = calls.find((c) => c.method === 'PUT')!
    expect(put.body).toEqual({
      content: usageSheet({ usage_notes: 'Followed by a noun.' }),
      base_enrichment_id: 7,
    })
  })

  it('keeps the edits when the sheet changed meanwhile, and reloads only on request', async () => {
    let current = sheetVersion()
    const calls = mockApi({
      'GET /items/1': term,
      'GET /items/1/sheet': () => Response.json(current),
      'GET /items/1/exercises': [],
      'PUT /items/1/sheet': () =>
        apiErrorResponse(409, 'sheet_changed', 'changed', { current_enrichment_id: 9 }),
    })
    renderApp('/library/items/1')
    await openSheet()
    await userEvent.click(await screen.findByRole('button', { name: 'Edit the sheet' }))
    const definition = screen.getByLabelText('Simple definition')
    await userEvent.clear(definition)
    await userEvent.type(definition, 'my own words')
    await userEvent.click(screen.getByRole('button', { name: 'Save the sheet' }))
    expect(await screen.findByText(/changed since you opened it/)).toBeInTheDocument()
    expect(screen.getByLabelText('Simple definition')).toHaveValue('my own words')

    // Someone else saved version 3: loading it needs a confirmation and drops the edits.
    current = sheetVersion({
      enrichment_id: 9,
      version: 3,
      content: usageSheet({ definition_simple: 'the newer definition' }),
    })
    await userEvent.click(screen.getByRole('button', { name: 'Load the latest version' }))
    await userEvent.click(screen.getByRole('button', { name: 'Keep my changes on screen' }))
    expect(screen.getByLabelText('Simple definition')).toHaveValue('my own words')
    await userEvent.click(screen.getByRole('button', { name: 'Load the latest version' }))
    await userEvent.click(screen.getByRole('button', { name: 'Yes, load it' }))
    await waitFor(() =>
      expect(screen.getByLabelText('Simple definition')).toHaveValue('the newer definition'),
    )
    expect(calls.filter((c) => c.method === 'PUT')).toHaveLength(1)
  })

  it('regenerates an edited sheet only after explicit consent', async () => {
    const calls = mockApi({
      'GET /items/1': detail(1, 'to account for', { sheet_status: 'edited' }),
      'GET /items/1/sheet': sheetVersion({
        sheet_status: 'edited',
        edited_by_user: true,
        edited_at: '2026-10-17T09:00:00Z',
      }),
      'GET /items/1/exercises': [],
      'POST /items/1/sheet/regenerate': (call) =>
        (call.body as { confirm_overwrite: boolean }).confirm_overwrite
          ? Response.json(report({ status: 'unavailable', reason: 'no_provider_configured' }))
          : apiErrorResponse(409, 'sheet_edited', 'edited'),
    })
    renderApp('/library/items/1')
    await openSheet()
    expect(await screen.findByText(/edited by you on/)).toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Generate a new version' }))
    const dialog = await screen.findByRole('alertdialog', { name: 'Replace your version?' })

    // Refusing sends nothing more.
    await userEvent.click(within(dialog).getByRole('button', { name: 'Keep my version' }))
    expect(screen.queryByRole('alertdialog')).not.toBeInTheDocument()
    const regenerations = () => calls.filter((c) => c.path === '/items/1/sheet/regenerate')
    expect(regenerations().map((c) => c.body)).toEqual([{ confirm_overwrite: false }])

    await userEvent.click(screen.getByRole('button', { name: 'Generate a new version' }))
    await userEvent.click(
      within(await screen.findByRole('alertdialog')).getByRole('button', {
        name: 'Replace my version',
      }),
    )
    expect(
      await screen.findByText(
        'No new version: no AI provider is set up. Your sheet is kept.',
      ),
    ).toBeInTheDocument()
    expect(regenerations().map((c) => c.body)).toEqual([
      { confirm_overwrite: false },
      { confirm_overwrite: false },
      { confirm_overwrite: true },
    ])
  })

  it('accepts a sheet typed by hand when there is none (degraded mode)', async () => {
    let saved: ReturnType<typeof sheetVersion> | null = null
    const calls = mockApi({
      'GET /items/1': detail(1, 'to account for', { sheet_status: 'none' }),
      'GET /items/1/sheet': () =>
        saved === null
          ? apiErrorResponse(404, 'sheet_not_found', 'none')
          : Response.json(saved),
      'GET /items/1/exercises': [],
      'PUT /items/1/sheet': () => {
        saved = sheetVersion({ edited_by_user: true, provider: null, model: null })
        return Response.json(saved)
      },
    })
    renderApp('/library/items/1')
    await openSheet()
    await userEvent.click(await screen.findByRole('button', { name: 'Write the sheet by hand' }))
    await userEvent.click(screen.getByRole('button', { name: 'Save the sheet' }))
    expect(screen.getByText(/at least a simple definition or a French translation/)).toBeInTheDocument()
    expect(calls.some((c) => c.method === 'PUT')).toBe(false)

    await userEvent.click(screen.getByRole('button', { name: 'Add: French translation' }))
    await userEvent.type(screen.getByLabelText('French translation 1'), 'tenir compte de')
    await userEvent.click(screen.getByRole('button', { name: 'Save the sheet' }))
    await screen.findByText('Saved as a new version.')
    const put = calls.find((c) => c.method === 'PUT')!.body as {
      content: { translation_fr: string[]; examples: unknown[] }
      base_enrichment_id: number | null
    }
    expect(put.base_enrichment_id).toBeNull()
    expect(put.content.translation_fr).toEqual(['tenir compte de'])
    expect(put.content.examples).toEqual([])
  })

  it('generates a missing sheet and explains an AI failure', async () => {
    const calls = mockApi({
      'GET /items/1': detail(1, 'to account for', { sheet_status: 'none' }),
      'GET /items/1/sheet': () => apiErrorResponse(404, 'sheet_not_found', 'none'),
      'GET /items/1/exercises': [],
      'POST /enrichment/run': report({ status: 'unavailable', reason: 'quota', item_ids: [1] }),
    })
    renderApp('/library/items/1')
    await openSheet()
    await userEvent.click(await screen.findByRole('button', { name: 'Generate with AI' }))
    expect(await screen.findByText(/No sheet generated: the free quota is used up/)).toBeInTheDocument()
    expect(calls.find((c) => c.path === '/enrichment/run')!.body).toEqual({ item_ids: [1] })
  })

  it('lists the versions and opens an old one read-only', async () => {
    mockApi({
      'GET /items/1': term,
      'GET /items/1/sheet': sheetVersion({ enrichment_id: 8, version: 2, edited_by_user: true }),
      'GET /items/1/exercises': [],
      'GET /items/1/sheet/versions': [
        sheetVersion({ enrichment_id: 8, version: 2, edited_by_user: true }),
        sheetVersion({
          enrichment_id: 7,
          version: 1,
          is_current: false,
          content: usageSheet({ translation_fr: ['expliquer'] }),
        }),
      ],
    })
    renderApp('/library/items/1')
    await openSheet()
    await userEvent.click(await screen.findByRole('button', { name: 'Show the versions' }))
    await userEvent.click(await screen.findByRole('button', { name: 'Open version 1' }))
    expect(screen.getByText('expliquer')).toBeInTheDocument()
    expect(screen.getByText('current')).toBeInTheDocument()
  })
})

describe('exercises on the term page', () => {
  const gapFill = exercise(5, 'gap_fill', {
    sentence: 'We ___ regional effects.',
    answer: 'account for',
    accepted: [],
  })

  it('edits an exercise and sends its whole content', async () => {
    const calls = mockApi({
      'GET /items/1': term,
      'GET /items/1/sheet': sheetVersion(),
      'GET /items/1/exercises': [gapFill],
      'PATCH /exercises/5': (call) =>
        Response.json({ ...gapFill, edited_by_user: true, content: (call.body as { content: object }).content }),
    })
    renderApp('/library/items/1')
    await openSheet()
    const block = await screen.findByRole('listitem', { name: 'Gap-fill' })
    await userEvent.click(within(block).getByRole('button', { name: 'Edit' }))
    await userEvent.type(within(block).getByLabelText('Other accepted answers'), 'accounts for{enter} ')
    await userEvent.click(within(block).getByRole('button', { name: 'Save' }))
    await waitFor(() =>
      expect(calls.find((c) => c.method === 'PATCH')!.body).toEqual({
        content: {
          sentence: 'We ___ regional effects.',
          answer: 'account for',
          accepted: ['accounts for'],
        },
      }),
    )
  })

  it('keeps the form and lists the reasons of a 422 invalid_exercise', async () => {
    mockApi({
      'GET /items/1': term,
      'GET /items/1/sheet': sheetVersion(),
      'GET /items/1/exercises': [gapFill],
      'PATCH /exercises/5': () =>
        apiErrorResponse(422, 'invalid_exercise', 'invalid', {
          errors: [{ loc: ['sentence'], message: 'the sentence must contain exactly one ___' }],
        }),
    })
    renderApp('/library/items/1')
    await openSheet()
    const block = await screen.findByRole('listitem', { name: 'Gap-fill' })
    await userEvent.click(within(block).getByRole('button', { name: 'Edit' }))
    const sentence = within(block).getByLabelText('Sentence')
    await userEvent.clear(sentence)
    await userEvent.type(sentence, 'We account for regional effects.')
    expect(within(block).getByText(/must contain the gap ___ exactly once/)).toBeInTheDocument()
    await userEvent.click(within(block).getByRole('button', { name: 'Save' }))
    expect(await within(block).findByText(/This exercise is not valid/)).toBeInTheDocument()
    expect(within(block).getByText(/the sentence must contain exactly one ___/)).toBeInTheDocument()
    expect(within(block).getByLabelText('Sentence')).toHaveValue('We account for regional effects.')
  })
})
